"""CB-326: отказ на входе в инструмент говорит словами ПРОЕКТА, а не чужой библиотеки.

ЧТО ЗА ГРАНИЦА И ПОЧЕМУ ОНА ЧЕТВЁРТАЯ. Модель ошибок этого проекта описывает
три канала, по которым отказ доходит до вызывающего: доменный отказ (текст
проекта, результат с признаком ошибки), авария (текст удерживается, в журнале
сервера), отказ слоя строгих имён аргументов (текст проекта, но ошибкой
протокола). Четвёртый канал — проверка аргументов на ВХОДЕ в инструмент, ДО его
тела, — не был описан вовсе, и клиент получал по нему текст библиотеки проверки
типов вместе со ссылкой на её сайт.

ЗАМЕР, ОТ КОТОРОГО ОТТАЛКИВАЕТСЯ ЭТОТ ФАЙЛ (пробники на этой же ветке:
`tests/manual/probe_p2_argument_refusal.py`, `probe_cb326_middleware_premise.py`;
снимки договора — `.claude/plans/cb326/`). Под обеими допущенными версиями
библиотеки `mcp` исход ПОБАЙТНО одинаков, и три факта из замера решают устройство
починки:

1. На отказе проверки схемы обработчик чужой библиотеки уже перехватил
   исключение и ВЕРНУЛ обычный результат с признаком ошибки. Значит промежуточный
   слой видит результат, а не исключение.
2. ДОМЕННЫЙ отказ приходит в ТОЙ ЖЕ форме. Значит переписать результат «задним
   числом» нельзя, не отличив одно от другого, а отличить их можно только по
   ТЕКСТУ чужой библиотеки — то есть по ровно той связи, ради разрыва которой
   заведена карта. Поэтому проверка делается ДО вызова, а не после.
3. Учётная таблица `tool_calls` СЕГОДНЯ считает такой отказ как отказ
   инструмента `add`. Улика самой карты («add отказывает в 11 процентах
   вызовов») взята из этой таблицы, поэтому новый слой обязан стоять ВНУТРИ
   учётного — иначе починка молча обесценит собственное основание карты.

ОБЛАСТЬ ПОЧИНКИ, ОБЪЯВЛЕННАЯ, А НЕ ПОДРАЗУМЕВАЕМАЯ. Слой берёт на себя ровно
один род беды — НЕ ПОДАНО обязательное поле, — потому что этот род решается
точно, из объявленной схемы самого инструмента, и не требует повторять чужую
проверку типов. Неверный ТИП поданного поля слой намеренно НЕ трогает: решать
его значило бы написать второй проверщик схемы рядом с настоящим, а два
проверщика расходятся, и расхождение выглядит как отказ на значении, которое
инструмент бы принял. Это записанный остаток, а не забытый случай, и
`test_a_wrong_type_is_deliberately_not_claimed_by_this_layer` держит границу.

ПОЧЕМУ ПРОГОН ЧЕРЕЗ НАСТОЯЩЕГО КЛИЕНТА, А НЕ ЧЕРЕЗ ВНУТРИПРОЦЕССНЫЙ ВЫЗОВ. Это
урок CB-310: десять тестов в наборе проверяли поверхность, построенную руками, и
все десять молчали о том, что видит клиент. Обещание этой карты дано клиенту,
поэтому и проверяется на клиенте. Обвязка живого сеанса заимствуется из
`tests/test_cb310_refusal_text.py`, а не копируется: она обращается к
внутренности чужой библиотеки, две допущенные версии которой уже ведут себя
по-разному, и вторая копия была бы вторым определением того же самого.
"""

from __future__ import annotations

import contextlib

import pytest

from codebugs import db, server, usage
from tests.test_cb310_refusal_text import call_over_the_wire

#: Признаки чужого происхождения текста. Ссылка на сайт — это буквальная
#: формулировка пункта 2 критерия приёмки; две другие добавлены потому, что
#: библиотека может убрать ссылку, не перестав говорить своим голосом, и тогда
#: проверка по одной ссылке зазеленела бы на неисправленной беде.
_FOREIGN_MARKS = ("errors.pydantic.dev", "validation error", "Arguments")


@pytest.fixture
def tracker(tmp_path):
    """Настоящий трекер на диске плюс фабрика соединений, которую берёт сервер."""
    project_dir = tmp_path / "project"
    project_dir.mkdir()
    project = str(project_dir)
    db.init_project(project)

    @contextlib.contextmanager
    def _conn():
        conn = db.connect(project)
        try:
            yield conn
        finally:
            conn.close()

    return project, _conn


def _built(tracker, mode: str = "findings"):
    _, factory = tracker
    return server._build_server(mode, factory)


def _innermost(exc: BaseException) -> BaseException:
    """Самое внутреннее исключение: группы исключений разворачиваются.

    Живой сеанс идёт под группой задач, и отказ протокола выходит наружу
    завёрнутым в группу. Без разворачивания проверка утверждала бы про класс
    обёртки, а не про класс отказа.
    """
    inner = getattr(exc, "exceptions", None)
    return _innermost(inner[0]) if inner else exc


def _rows(tracker):
    _, factory = tracker
    with factory() as conn:
        return usage.usage_summary(conn)["rows"]


class TestTheRefusalSpeaksTheProjectsWords:
    """Предмет карты: не поданное обязательное поле отказывается словами проекта."""

    def test_a_missing_required_field_is_named_in_the_projects_own_text(self, tracker):
        """Имя пропущенного поля обязано сохраниться: сегодняшний чужой текст
        называет `severity`, и это весь полезный ответ. Починка, которая
        избавилась бы от чужой марки ценой имени поля, была бы ухудшением.

        ЗЕЛЁН ПО ОБЕ СТОРОНЫ ПРАВКИ, и это его назначение: он закрепляет
        СОДЕРЖАНИЕ, которое правка обязана сохранить, а не отличие, которое она
        вносит. Читателю это сказано вслух, иначе такой тест не отличить от
        сломанного (правило `tests/CLAUDE.md`).
        """
        is_error, text = call_over_the_wire(
            _built(tracker), "add", {"category": "x", "file": "y", "description": "z"}
        )

        assert is_error is True
        assert "severity" in text
        assert "add" in text

    def test_the_answer_carries_no_pointer_to_the_validation_librarys_site(self, tracker):
        """Буквальный пункт 2 критерия приёмки: чужой марки в ответе нет."""
        _, text = call_over_the_wire(
            _built(tracker), "add", {"category": "x", "file": "y", "description": "z"}
        )

        for mark in _FOREIGN_MARKS:
            assert mark not in text, f"в ответе осталась чужая марка {mark!r}: {text!r}"

    def test_two_missing_fields_are_both_named(self, tracker):
        """Перечисление, а не первое попавшееся имя. Чужая библиотека
        перечисляет оба поля, и потеря второго при переходе на свой текст была
        бы потерей содержания, замаскированной под починку.

        ЗЕЛЁН ПО ОБЕ СТОРОНЫ ПРАВКИ — закрепляет сохраняемое содержание.
        """
        _, text = call_over_the_wire(_built(tracker), "add", {"category": "x", "description": "z"})

        assert "severity" in text
        assert "file" in text

    def test_the_refusal_is_a_result_and_not_a_protocol_error(self, tracker):
        """ГРАНИЦА, которую нельзя переходить: слияние двух каналов в один не
        является целью. Отказ проверки аргументов сегодня приходит РЕЗУЛЬТАТОМ
        с признаком ошибки, и клиентская библиотека его возвращает; отказ слоя
        строгих имён приходит ошибкой протокола, и клиентская библиотека его
        ПОДНИМАЕТ. Это разные способы обработки на стороне вызывающего, поэтому
        превращение первого во второе сломало бы клиентов, ничего не выиграв.

        ЗЕЛЁН ПО ОБЕ СТОРОНЫ ПРАВКИ — закрепляет сохраняемую ФОРМУ ответа.
        Мутант, поднимающий отказ протокола вместо возврата результата, красит
        его; он и записан в журнале брифа под этим номером.
        """
        is_error, text = call_over_the_wire(
            _built(tracker), "add", {"category": "x", "file": "y", "description": "z"}
        )

        assert is_error is True
        assert text, "отказ обязан нести текст, иначе это безымянная авария CB-310"

    def test_the_required_set_is_read_from_the_tools_own_schema(self, tracker):
        """Слой обязан быть общим, а не написанным под инструмент `add`.
        Проверяется на другом инструменте с другим набором обязательных полей:
        у требований это `req_id`, которого у находок нет вовсе."""
        is_error, text = call_over_the_wire(
            _built(tracker, "reqs"), "reqs_add", {"description": "z"}
        )

        assert is_error is True
        assert "req_id" in text
        for mark in _FOREIGN_MARKS:
            assert mark not in text


class TestTheOtherChannelsAreUntouched:
    """Контроль. Проверка, у которой нет случаев, обязанных не измениться, не
    умеет отличить «ничего лишнего не сломалось» от «смотрит не туда».

    ВЕСЬ ЭТОТ КЛАСС ЗЕЛЁН ПО ОБЕ СТОРОНЫ ПРАВКИ, и иначе быть не может: он про
    поведение, которое правка обязана оставить нетронутым. Его краснота
    означала бы, что новый слой захватил чужой канал, — то есть ровно ту
    границу, которую бриф запрещает переходить.
    """

    def test_an_undeclared_argument_name_still_arrives_as_a_protocol_error(self, tracker):
        """Слой строгих имён аргументов решает ДРУГОЙ вопрос, и его нынешняя
        работа не входит в задание этого юнита."""
        with pytest.raises(BaseException) as excinfo:  # noqa: B017 — предмет и есть форма
            call_over_the_wire(
                _built(tracker),
                "add",
                {"severity": "low", "category": "x", "file": "y", "description": "z", "bogus": 1},
            )

        assert "Unknown argument(s)" in str(_innermost(excinfo.value))

    def test_a_domain_refusal_still_carries_its_own_text(self, tracker):
        """Доменный отказ приходит в той же ФОРМЕ, что и отказ проверки
        аргументов, поэтому именно он показал бы, что новый слой хватает
        лишнее."""
        is_error, text = call_over_the_wire(
            _built(tracker), "update", {"finding_id": "CB-1", "status": "bogus"}
        )

        assert is_error is True
        assert "Invalid finding status" in text

    def test_an_unknown_tool_name_is_still_answered_by_the_sdk(self, tracker):
        """Слой строгих имён намеренно оставляет несуществующее имя инструмента
        чужой библиотеке — «не наше дело отвечать». Новый слой обязан вести себя
        так же, иначе он подменит собой чужой ответ на чужой вопрос."""
        is_error, text = call_over_the_wire(_built(tracker), "no_such_tool", {"anything": 1})

        assert is_error is True
        assert "no_such_tool" in text
        assert "Missing required" not in text

    def test_a_complete_call_still_runs(self, tracker):
        """Обратная сторона: слой, отказывающий всем, прошёл бы каждую проверку
        выше. `new_category` обязателен — в пустом трекере любая категория новая
        и её появление огорожено отдельным гейтом (CB-60)."""
        is_error, text = call_over_the_wire(
            _built(tracker),
            "add",
            {
                "severity": "low",
                "category": "x",
                "file": "y",
                "description": "z",
                "new_category": True,
            },
        )

        assert is_error is False, text
        assert '"dedup_action": "created"' in text

    def test_a_wrong_type_is_deliberately_not_claimed_by_this_layer(self, tracker):
        """ОБЪЯВЛЕННЫЙ ОСТАТОК, а не забытый случай.

        Поле подано — значит вопрос «не подано ли обязательное поле» отвечен
        утвердительно, и слой пропускает вызов дальше. Разбираться с ТИПОМ
        значит написать второй проверщик схемы рядом с настоящим; два
        проверщика расходятся, и расхождение выглядит как отказ на значении,
        которое инструмент бы принял.

        Проверка утверждает про СВОЁ поведение, а не про чужой текст: чужой
        текст принадлежит библиотеке, допущенной диапазоном версий, и
        закреплять его здесь значило бы делать набор тестов хрупким к
        обновлению, которое проект разрешает.
        """
        is_error, text = call_over_the_wire(
            _built(tracker), "add", {"severity": 5, "category": "x", "file": "y",
                                     "description": "z"}
        )

        assert is_error is True
        assert "Missing required" not in text


class TestPlacementInTheChain:
    """Размещение слоя. Это не деталь: оно решает, что видит учёт вызовов.

    ОБА ТЕСТА ЗЕЛЕНЫ ПО ОБЕ СТОРОНЫ ПРАВКИ — они закрепляют учёт, каким он был
    ДО неё. Различающим их делает не правка, а МУТАНТ: перестановка нового слоя
    наружу учётного красит первый из них, и только его. Разница между «правка
    сохранила» и «мутант сломал» здесь и есть весь смысл этих двух проверок.
    """

    def test_a_missing_field_refusal_is_still_counted_as_a_failure_of_that_tool(self, tracker):
        """ОРАКУЛ РАЗМЕЩЕНИЯ. Сегодня такой вызов записывается в `tool_calls`
        как отказ инструмента `add`, потому что чужая библиотека перехватывает
        его ВНУТРИ, за спиной учётного слоя. Новый слой, поставленный снаружи
        учётного, отобрал бы у таблицы эту запись — не изменив при этом ни
        байта в ответе клиенту, то есть незаметно для всех остальных проверок.
        А улика самой карты CB-326 взята именно из этой таблицы."""
        call_over_the_wire(
            _built(tracker), "add", {"category": "x", "file": "y", "description": "z"}
        )

        rows = _rows(tracker)
        assert [(r["tool_name"], r["calls"], r["failures"]) for r in rows] == [("add", 1, 1)]

    def test_an_undeclared_argument_refusal_is_still_not_counted(self, tracker):
        """Вторая половина того же вопроса, и она про ДРУГОЙ канал. Отказ слоя
        строгих имён не считается сегодня — это записанное решение
        (`install_usage_tracking`), а не случайность порядка вызовов, — и новый
        слой не имеет права его изменить ни в одну сторону."""
        with contextlib.suppress(BaseException):
            call_over_the_wire(
                _built(tracker),
                "add",
                {"severity": "low", "category": "x", "file": "y", "description": "z", "bogus": 1},
            )

        assert _rows(tracker) == []


class TestTheLayerIsActuallyInstalled:
    """Слой можно написать, проверить и никогда не подключить — и набор тестов
    останется зелёным. Тот же урок отдельно закреплён для сторожей харнеса
    рабочих деревьев (`tests/test_worktree_harness.py`), и он же применяется
    здесь: порядок в цепочке проверяется отдельно от поведения, чтобы поломка
    называла свою причину, а не только свои последствия."""

    def test_build_server_puts_the_layer_inside_usage_tracking(self, tracker):
        """Порядок списка — снаружи внутрь. Строгие имена снаружи (их отказ не
        считается), учёт посередине, обязательные поля внутри (их отказ
        считается).

        Утверждение делается о ВЗАИМНОМ порядке слоёв ЭТОГО пакета, а не о всём
        списке, и это не послабление, а точность. Замерено: чужая библиотека
        сама кладёт в тот же список два своих слоя впереди наших — под обеими
        допущенными версиями одинаково. Они не принадлежат этому проекту, и
        закрепление их присутствия покрасило бы набор тестов при обновлении
        библиотеки по причине, никак не связанной с этой картой. Свои слои
        отбираются по признаку, который у чужих отсутствует: они простые
        функции и потому несут `__name__`.
        """
        built = _built(tracker)

        ours = [mw.__name__ for mw in built.middleware if hasattr(mw, "__name__")]
        assert ours == [
            "reject_unknown_arguments",
            "record_tool_usage",
            "refuse_missing_required_arguments",
        ]
